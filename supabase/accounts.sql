-- DAQQA accounts: per-order costs, expenses, returns, delivery location, Google Sheet link (admin only)

-- returns are a status of their own; the customer can share a map link with the order
alter table public.shop_orders drop constraint if exists shop_orders_status_check;
alter table public.shop_orders add constraint shop_orders_status_check check (status in ('new','confirmed','shipped','delivered','cancelled','returned'));
alter table public.shop_orders add column if not exists location text;

-- stock (and the "left" number customers see) comes back when an order is cancelled or returned, and is taken again if it is reopened
create or replace function public.shop_order_stock() returns trigger language plpgsql security definer set search_path = public as $$
declare was_out boolean := old.status in ('cancelled','returned'); is_out boolean := new.status in ('cancelled','returned');
begin
  if is_out and not was_out then
    update public.shop_products p set stock = case when p.stock is null then null else p.stock + i.qty end,
      shown_left = case when p.shown_left is null then null else p.shown_left + i.qty end
    from public.shop_order_items i where i.order_id = new.id and i.product_id = p.id;
  elsif was_out and not is_out then
    update public.shop_products p set stock = case when p.stock is null then null else greatest(0, p.stock - i.qty) end,
      shown_left = case when p.shown_left is null then null else greatest(0, p.shown_left - i.qty) end
    from public.shop_order_items i where i.order_id = new.id and i.product_id = p.id;
  end if;
  return new;
end $$;

-- money behind each order: what it sold for, what it cost, shipping and who paid it
create table if not exists public.shop_order_fin (
  order_id bigint primary key references public.shop_orders(id) on delete cascade,
  sale numeric(12,2) not null default 0,
  cost numeric(12,2) not null default 0,
  ship_cost numeric(12,2) not null default 0,
  ship_payer text not null default 'buyer' check (ship_payer in ('buyer','me')),
  return_loss numeric(12,2) not null default 0,
  updated_at timestamptz not null default now()
);
-- last cost price per product, so the next order fills it in by itself
create table if not exists public.shop_product_costs (
  product_id bigint primary key references public.shop_products(id) on delete cascade,
  cost numeric(12,2) not null default 0,
  updated_at timestamptz not null default now()
);
create table if not exists public.shop_expenses (
  id bigint generated by default as identity primary key,
  spent_on date not null default current_date,
  category text not null default 'أخرى',
  amount numeric(12,2) not null check (amount >= 0),
  note text,
  created_at timestamptz not null default now()
);
-- private settings (the sheet link must not be readable by visitors)
create table if not exists public.shop_admin_settings (
  id int primary key default 1 check (id = 1),
  sheet_url text,
  sheet_secret text
);
insert into public.shop_admin_settings (id) values (1) on conflict do nothing;

do $$ declare t text; begin
  foreach t in array array['shop_order_fin','shop_product_costs','shop_expenses','shop_admin_settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "admin all" on public.%I', t);
    execute format('create policy "admin all" on public.%I for all to authenticated using (public.shop_is_admin()) with check (public.shop_is_admin())', t);
  end loop;
end $$;

-- sales made outside the website (shop, WhatsApp, …) — counted in sales and net profit
create table if not exists public.shop_offline_sales (
  id bigint generated by default as identity primary key,
  sold_on date not null default current_date,
  product_id bigint references public.shop_products(id) on delete set null,
  name text not null,
  qty int not null default 1 check (qty > 0),
  price numeric(12,2) not null default 0 check (price >= 0),
  cost numeric(12,2) not null default 0 check (cost >= 0),
  ship_cost numeric(12,2) not null default 0 check (ship_cost >= 0),
  ship_payer text not null default 'buyer' check (ship_payer in ('buyer','me')),
  seller text,
  note text,
  created_at timestamptz not null default now()
);
alter table public.shop_offline_sales enable row level security;
drop policy if exists "admin all" on public.shop_offline_sales;
create policy "admin all" on public.shop_offline_sales for all to authenticated using (public.shop_is_admin()) with check (public.shop_is_admin());
