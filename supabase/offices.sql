-- «المكاتب» (admin only): offices we deal with — name, WhatsApp, phone, Telegram link, address, GPS (map link or lat,lng), notes
-- Run once in Supabase → SQL Editor.
create table if not exists public.shop_offices (
  id bigint generated by default as identity primary key,
  name text not null,
  wa text,
  phone text,
  tg text,
  address text,
  gps text,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.shop_offices enable row level security;
drop policy if exists "admin all" on public.shop_offices;
create policy "admin all" on public.shop_offices for all to authenticated using (public.shop_is_admin()) with check (public.shop_is_admin());
alter table public.shop_offices add column if not exists address text;
alter table public.shop_offices add column if not exists gps text;
