-- ---------- orders ----------
create table if not exists public.shop_orders (
  id bigint generated by default as identity primary key,
  code text not null unique,
  user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  phone text not null,
  city text,
  address text,
  notes text,
  subtotal numeric(12,2) not null default 0,
  savings numeric(12,2) not null default 0,
  shipping numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  status text not null default 'new' check (status in ('new','confirmed','shipped','delivered','cancelled')),
  admin_note text,
  created_at timestamptz not null default now()
);
create index if not exists shop_orders_user_idx on public.shop_orders(user_id);
create index if not exists shop_orders_created_idx on public.shop_orders(created_at desc);

create table if not exists public.shop_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.shop_orders(id) on delete cascade,
  product_id bigint references public.shop_products(id) on delete set null,
  name text not null,
  image text,
  qty int not null check (qty > 0),
  unit_price numeric(12,2) not null,
  original_price numeric(12,2) not null,
  line_total numeric(12,2) not null
);
create index if not exists shop_order_items_order_idx on public.shop_order_items(order_id);

alter table public.shop_orders enable row level security;
alter table public.shop_order_items enable row level security;
-- orders are created only through shop_place_order (no direct insert)
drop policy if exists "orders: owner or admin read" on public.shop_orders;
create policy "orders: owner or admin read" on public.shop_orders
  for select to authenticated using (user_id = auth.uid() or public.shop_is_admin());
drop policy if exists "orders: admin update" on public.shop_orders;
create policy "orders: admin update" on public.shop_orders
  for update to authenticated using (public.shop_is_admin()) with check (public.shop_is_admin());
drop policy if exists "orders: admin delete" on public.shop_orders;
create policy "orders: admin delete" on public.shop_orders
  for delete to authenticated using (public.shop_is_admin());
drop policy if exists "items: owner or admin read" on public.shop_order_items;
create policy "items: owner or admin read" on public.shop_order_items
  for select to authenticated using (
    public.shop_is_admin() or exists (select 1 from public.shop_orders o where o.id = order_id and o.user_id = auth.uid())
  );

-- place an order: prices, stock and shipping are computed on the server
create or replace function public.shop_place_order(customer jsonb, items jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  s public.shop_settings;
  it jsonb; p public.shop_products; q int;
  v_sub numeric := 0; v_orig numeric := 0; v_ship numeric := 0; v_unit numeric;
  v_code text; v_id bigint;
begin
  if coalesce(trim(customer->>'name'), '') = '' or coalesce(trim(customer->>'phone'), '') = '' then
    raise exception 'اكتب الاسم ورقم التليفون';
  end if;
  if items is null or jsonb_array_length(items) = 0 then raise exception 'السلة فاضية'; end if;
  if jsonb_array_length(items) > 30 then raise exception 'عدد المنتجات كبير'; end if;

  loop
    v_code := 'DQ-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
    exit when not exists (select 1 from public.shop_orders where code = v_code);
  end loop;

  insert into public.shop_orders (code, user_id, customer_name, phone, city, address, notes)
  values (v_code, auth.uid(), left(trim(customer->>'name'), 120), left(trim(customer->>'phone'), 30),
          left(customer->>'city', 60), left(customer->>'address', 400), left(customer->>'notes', 1000))
  returning id into v_id;

  for it in select * from jsonb_array_elements(items) loop
    q := greatest(1, least(20, coalesce((it->>'qty')::int, 1)));
    select * into p from public.shop_products where id = (it->>'id')::bigint and active for update;
    if not found then raise exception 'منتج مش متاح دلوقتي'; end if;
    if p.stock is not null and p.stock < q then raise exception 'الكمية المطلوبة من % مش متاحة دلوقتي، قلّل العدد', p.name; end if;
    v_unit := case when p.sale_price is not null and p.sale_price < p.price then p.sale_price else p.price end;
    insert into public.shop_order_items (order_id, product_id, name, image, qty, unit_price, original_price, line_total)
    values (v_id, p.id, p.name, p.images[1], q, v_unit, p.price, v_unit * q);
    update public.shop_products set stock = case when stock is null then null else stock - q end,
      shown_left = case when shown_left is null then null else greatest(0, shown_left - q) end
    where id = p.id;
    v_sub := v_sub + v_unit * q; v_orig := v_orig + p.price * q;
  end loop;

  select * into s from public.shop_settings where id = 1;
  v_ship := case when s.free_shipping_over is not null and v_sub >= s.free_shipping_over then 0 else coalesce(s.shipping_fee, 0) end;
  update public.shop_orders set subtotal = v_sub, savings = v_orig - v_sub, shipping = v_ship, total = v_sub + v_ship where id = v_id;
  return jsonb_build_object('id', v_id, 'code', v_code, 'total', v_sub + v_ship);
end $$;
grant execute on function public.shop_place_order(jsonb, jsonb) to anon, authenticated;

-- give stock back when an order is cancelled (and take it again if un-cancelled)
create or replace function public.shop_order_stock() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'cancelled' and old.status <> 'cancelled' then
    update public.shop_products p set stock = p.stock + i.qty from public.shop_order_items i where i.order_id = new.id and i.product_id = p.id and p.stock is not null;
  elsif old.status = 'cancelled' and new.status <> 'cancelled' then
    update public.shop_products p set stock = greatest(0, p.stock - i.qty) from public.shop_order_items i where i.order_id = new.id and i.product_id = p.id and p.stock is not null;
  end if;
  return new;
end $$;
drop trigger if exists shop_order_stock on public.shop_orders;
create trigger shop_order_stock after update of status on public.shop_orders for each row execute function public.shop_order_stock();

-- guests track an order with its code + phone
create or replace function public.shop_track_order(p_code text, p_phone text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('code', o.code, 'status', o.status, 'total', o.total, 'created_at', o.created_at,
    'items', coalesce((select jsonb_agg(jsonb_build_object('name', i.name, 'qty', i.qty, 'image', i.image)) from public.shop_order_items i where i.order_id = o.id), '[]'::jsonb))
  from public.shop_orders o
  where o.code = upper(trim(p_code))
    and regexp_replace(o.phone, '\D', '', 'g') = regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
$$;
grant execute on function public.shop_track_order(text, text) to anon, authenticated;

