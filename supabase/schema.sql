-- ---------- admins ----------
create table if not exists public.shop_admins (
  email text primary key
);
insert into public.shop_admins (email) values ('daqqastore@gmail.com') on conflict do nothing;
alter table public.shop_admins enable row level security;

create or replace function public.shop_is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.shop_admins a
    where lower(a.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;
grant execute on function public.shop_is_admin() to anon, authenticated;

-- ---------- products ----------
create table if not exists public.shop_products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text,
  category text not null default 'men' check (category in ('men','women','unisex')),
  kind text not null default 'watches',
  style text,
  colors text[] not null default '{}',
  colors_label text,
  luxury boolean not null default false,
  description text,
  price numeric(12,2) not null default 0 check (price >= 0),
  sale_price numeric(12,2) check (sale_price is null or sale_price >= 0),
  images text[] not null default '{}',
  stock int check (stock >= 0),                      -- null = not tracked (always orderable)
  show_left boolean not null default false,          -- show customers a "only N left" line
  shown_left int check (shown_left is null or shown_left >= 0), -- the N shown (set by the admin, goes down with each order)
  featured boolean not null default false,
  active boolean not null default true,
  sort int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.shop_products add column if not exists show_left boolean not null default false;
alter table public.shop_products add column if not exists shown_left int check (shown_left is null or shown_left >= 0);
alter table public.shop_products alter column stock drop not null;
alter table public.shop_products alter column stock set default null;
alter table public.shop_products enable row level security;
drop policy if exists "products: public read active" on public.shop_products;
create policy "products: public read active" on public.shop_products
  for select using (active or public.shop_is_admin());
drop policy if exists "products: admin write" on public.shop_products;
create policy "products: admin write" on public.shop_products
  for all to authenticated using (public.shop_is_admin()) with check (public.shop_is_admin());

