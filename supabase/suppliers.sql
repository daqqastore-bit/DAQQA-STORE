-- Suppliers (admin only): who we buy from, which products, and the cost of each
-- items = [{p: product id, c: cost price, n: note}]
create table if not exists public.shop_suppliers (
  id bigint generated by default as identity primary key,
  name text,
  phone text,
  address text,
  note text,
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.shop_suppliers enable row level security;
create policy "admin all" on public.shop_suppliers for all to authenticated using (public.shop_is_admin()) with check (public.shop_is_admin());
